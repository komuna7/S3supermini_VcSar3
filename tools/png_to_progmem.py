#!/usr/bin/env python3
"""Convert V3 PNG frame sequences to SSD1306-friendly 1-bit PROGMEM data."""

from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ANIMATIONS = ROOT / "animations"
OUTPUT = ROOT / "V3AnimationFrames.h"
WIDTH = 27
HEIGHT = 32
STRIDE = (WIDTH + 7) // 8
SEQUENCES = [
    ("sitting", "01 sitting"),
    ("goodbye", "02 saygoodbye"),
    ("walking", "03 walk1"),
    ("running", "04 run"),
    ("car", "05 car"),
]


def frame_bytes(path: Path) -> list[int]:
    image = Image.open(path).convert("L")
    if image.size != (WIDTH, HEIGHT):
        raise ValueError(f"{path} is {image.size}; expected {WIDTH}x{HEIGHT}")
    pixels = image.load()
    data = []
    for y in range(HEIGHT):
        for byte_x in range(STRIDE):
            value = 0
            for bit in range(8):
                x = byte_x * 8 + bit
                if x < WIDTH and pixels[x, y] >= 128:
                    value |= 0x80 >> bit
            data.append(value)
    return data


def main() -> None:
    lines = [
        "// Generated by tools/png_to_progmem.py; do not edit by hand.",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        f"constexpr uint8_t V3_ANIMATION_WIDTH = {WIDTH};",
        f"constexpr uint8_t V3_ANIMATION_HEIGHT = {HEIGHT};",
        f"constexpr uint8_t V3_ANIMATION_STRIDE = {STRIDE};",
        f"constexpr uint16_t V3_ANIMATION_FRAME_BYTES = {STRIDE * HEIGHT};",
        "",
    ]
    for name, directory in SEQUENCES:
        files = sorted((ANIMATIONS / directory).glob("*.png"))
        if not files:
            raise ValueError(f"No PNG frames found in {directory}")
        lines.append(f"constexpr uint8_t V3_{name.upper()}_FRAME_COUNT = {len(files)};")
        lines.append(f"static const uint8_t PROGMEM v3_{name}_frames[][V3_ANIMATION_FRAME_BYTES] = {{")
        for path in files:
            values = frame_bytes(path)
            formatted = ", ".join(f"0x{value:02X}" for value in values)
            lines.append(f"  {{{formatted}}},")
        lines.extend(["};", ""])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
